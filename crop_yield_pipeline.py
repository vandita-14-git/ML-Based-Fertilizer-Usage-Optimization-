# 3. CLEAN
# ============================================================================
def clean_data(df, R):
    section("3. Clean the data")
    # Would filling by soil type be more accurate than one global median? Test it first.
    spread = {}
    for col in IMPUTE_COLS:
        med = df.groupby("soil_type")[col].median()
        spread[col] = {"lowest_group_median": float(med.min()), "highest_group_median": float(med.max())}
        print(f"  {col}: medians by soil type range {med.min():.2f} to {med.max():.2f}")
    # (a) columns missing ~2 cells: drop those rows
    clean = df.dropna(subset=FEW_MISSING).copy()
    dropped = len(df) - len(clean)
    # (b) columns missing 8-12%: fill with the global median
    fills = {}
    for col in IMPUTE_COLS:
        med = float(clean[col].median())
        n = int(clean[col].isnull().sum())
        clean[col] = clean[col].fillna(med)
        fills[col] = {"cells_filled": n, "median_used": med}
    R["clean"] = {"rows_dropped": int(dropped), "rows_kept": int(len(clean)), "fills": fills,
                  "median_by_soil_type_spread": spread, "missing_left": int(clean.isnull().sum().sum())}
    print(f"Rows dropped: {dropped} | rows kept: {len(clean):,} | fills: {fills}")
    return clean


