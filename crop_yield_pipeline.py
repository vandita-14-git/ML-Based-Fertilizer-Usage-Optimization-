# 5. PREPARE
# ============================================================================
def prepare(clean, R):
    section("5. Prepare: encode words as numbers and split 80/20")
    data = clean.copy()
    data["fertilized"] = data["fertilized"].map({"no": 0, "yes": 1})                    # two values -> 0/1
    data["seed_quality"] = data["seed_quality"].map({"low": 0, "medium": 1, "high": 2})  # real order -> 0/1/2
    data = pd.get_dummies(data, columns=NOMINAL, drop_first=True, dtype=int)            # no order -> one-hot
    X = data.drop(columns=[TARGET]); y = data[TARGET]
    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.2, random_state=SEED)
    R["split"] = {"features": int(X.shape[1]), "train_rows": int(len(X_train)), "test_rows": int(len(X_test)),
                  "train_mean_yield": float(y_train.mean()), "test_mean_yield": float(y_test.mean()),
                  "train_fertilized_share": float(X_train["fertilized"].mean()),
                  "test_fertilized_share": float(X_test["fertilized"].mean()),
                  "feature_names": list(X.columns)}
    print(f"Features: {X.shape[1]} | train {len(X_train):,} | test {len(X_test):,}")
    return X_train, X_test, y_train, y_test


# ============================================================================
# 6. MODELS
# ============================================================================
def models(X_train, X_test, y_train, y_test, n_trees, R, outdir):
    section("6. Models: the ladder from a guess to a random forest")
    avg = float(y_train.mean())
    avg_tr, avg_te = np.full(len(y_train), avg), np.full(len(y_test), avg)

    # Level 1: one fact only
    m1 = LinearRegression().fit(X_train[["fertilized"]], y_train)
    one_te = m1.predict(X_test[["fertilized"]])
    R["one_fact"] = {"intercept": float(m1.intercept_), "weight": float(m1.coef_[0])}

    # Level 2: straight line on all facts
    lin = LinearRegression().fit(X_train, y_train)
    weights = pd.Series(lin.coef_, index=X_train.columns)
    R["linear_weights"] = {k: float(v) for k, v in weights.items()}
    R["linear_intercept"] = float(lin.intercept_)

    # Level 3: decision trees of growing depth (overfitting experiment)
    section("   decision trees: more questions, help or hurt?")
    trees, sweep = {}, []
    for depth in [1, 2, 3, 5, 8, 12, 20, None]:
        t = DecisionTreeRegressor(max_depth=depth, random_state=SEED).fit(X_train, y_train)
        trees[depth] = t
        sweep.append({"depth": "no limit" if depth is None else depth,
                      "train_r2": float(r2_score(y_train, t.predict(X_train))),
                      "test_r2": float(r2_score(y_test, t.predict(X_test))),
                      "final_boxes": int(t.get_n_leaves())})
        print(f"   depth {sweep[-1]['depth']!s:>8}: train R2 {sweep[-1]['train_r2']:.3f} | test R2 {sweep[-1]['test_r2']:.3f}")
    R["tree_sweep"] = sweep
    best = max(sweep, key=lambda s: s["test_r2"])
    best_depth = None if best["depth"] == "no limit" else best["depth"]
    R["best_tree_depth"] = best["depth"]
    small = DecisionTreeRegressor(max_depth=3, random_state=SEED).fit(X_train, y_train)
    R["tree_text_depth3"] = export_text(small, feature_names=list(X_train.columns), decimals=1)

    # Level 4: random forest
    t0 = time.time()
    forest = RandomForestRegressor(n_estimators=n_trees, min_samples_leaf=MIN_LEAF, n_jobs=-1, random_state=SEED)
    forest.fit(X_train, y_train)
    R["forest_train_seconds"] = float(time.time() - t0)
    print(f"   forest of {n_trees} trees trained in {time.time() - t0:.0f}s")

    # Scores for every model, on study and hidden fields
    def both(model=None, tr=None, te=None):
        p_tr = model.predict(X_train) if model is not None else tr
        p_te = model.predict(X_test) if model is not None else te
        return {"train_rmse": rmse(y_train, p_tr), "train_r2": float(r2_score(y_train, p_tr)),
                "test_rmse": rmse(y_test, p_te), "test_r2": float(r2_score(y_test, p_te))}
    scores = {"Average guess": both(tr=avg_tr, te=avg_te),
              "One fact (fertilized)": {"train_rmse": rmse(y_train, m1.predict(X_train[["fertilized"]])),
                                         "train_r2": float(r2_score(y_train, m1.predict(X_train[["fertilized"]]))),
                                         "test_rmse": rmse(y_test, one_te), "test_r2": float(r2_score(y_test, one_te))},
              "Straight line (all facts)": both(lin),
              f"One tree (depth {best['depth']})": both(trees[best_depth]),
              "One tree (no limit)": both(trees[None]),
              f"Random forest ({n_trees} trees)": both(forest)}
    R["model_scores"] = scores
    for k, v in scores.items():
        print(f"   {k:<28} test RMSE {v['test_rmse']:.3f} | test R2 {v['test_r2']:.3f} | train R2 {v['train_r2']:.3f}")

    # --- one prediction worked by hand + the trees voting on one real field
    field = X_test.iloc[[0]]
    contributions = weights * X_test.iloc[0]
    votes = [float(t.predict(field.values)[0]) for t in forest.estimators_]
    R["hand_example"] = {"intercept": float(lin.intercept_), "sum_weighted": float(contributions.sum()),
                         "prediction": float(lin.predict(field)[0]), "actual": float(y_test.iloc[0]),
                         "top_contributors": {k: float(v) for k, v in contributions.reindex(
                             contributions.abs().sort_values(ascending=False).index[:6]).items()}}
    R["vote"] = {"first_trees": votes[:8], "forest_average": float(np.mean(votes)),
                 "straight_line": float(lin.predict(field)[0]), "actual": float(y_test.iloc[0]), "n_trees": n_trees}

    # --- more trees voting
    all_preds = np.array([t.predict(X_test.values) for t in forest.estimators_])
    ks = sorted({k for k in [1, 3, 10, 30, n_trees] if k <= n_trees})
    more = [{"trees": k, "test_r2": float(r2_score(y_test, all_preds[:k].mean(axis=0))),
             "test_rmse": rmse(y_test, all_preds[:k].mean(axis=0))} for k in ks]
    R["more_trees"] = more

    # --- importance
    imp = pd.Series(forest.feature_importances_, index=X_train.columns).sort_values(ascending=False)
    R["feature_importance_top10"] = {k: float(v) for k, v in imp.head(10).items()}

    # ---------------- charts ----------------
    # 6a. ladder (typical mistake)
    names = ["Average guess", "Straight line (all facts)", f"One tree (depth {best['depth']})", f"Random forest ({n_trees} trees)"]
    vals = [scores[n]["test_rmse"] for n in names]
    r2s = [scores[n]["test_r2"] for n in names]
    fig, ax = plt.subplots(figsize=(9, 4.8))
    bars = ax.bar(["Average\nguess", "Straight line\n(all facts)", f"One tree\n(depth {best['depth']})", f"Random forest\n({n_trees} trees)"],
                  vals, color=[C["gray"], C["orange"], C["purple"], C["green"]])
    for b, v, r2 in zip(bars, vals, r2s):
        ax.text(b.get_x() + b.get_width() / 2, v + 0.06, f"{v:.2f} t\nR\u00b2 = {nz(r2):.2f}", ha="center")
    ax.set_ylim(0, max(vals) * 1.3); ax.set_ylabel("Typical mistake on hidden fields (tons)\nlower is better")
    ax.set_title(f"Each step of the ladder shrinks the typical mistake: {vals[0]:.1f} to {vals[-1]:.1f} tons")
    save(fig, outdir, "08_model_ladder.png")

    # 6b. overfitting curve
    labels = [str(s["depth"]) for s in sweep]
    fig, ax = plt.subplots(figsize=(8.5, 5))
    ax.plot(labels, [s["train_r2"] for s in sweep], "o-", color=C["blue"], lw=2.5, label="Study fields (practice paper)")
