#!/usr/bin/env python3
"""
Where does more fertilizer stop paying off?
A machine-learning method demonstration on a synthetic crop-yield dataset
==========================================================================

This single script runs the WHOLE project, start to finish:

    1. Load and profile the raw data
    2. Reality check: does the data behave like real farms?
    3. Clean the data (drop a few rows, median-fill three columns)
    4. Explore: target, fertilizer effect, correlations, hills, fertilizer gain by condition
    5. Prepare: encode words as numbers, split 80/20 into a study set and a hidden exam set
    6. Models: average guess -> one fact -> straight line -> decision trees -> random forest
    7. What-if test: how many extra tons does fertilizer add to each field?
    8. Nutrient response curves, the 95% plateau rule, how many fields lie beyond it
    9. Sensitivity of the answer to the rule, and a "trim the excess" what-if
   10. Draw the flowcharts used in the README

Everything it produces goes to:
    <outdir>/*.png        every chart and flowchart
    <results>             results.json with every number quoted in the README

USAGE
    pip install -r requirements.txt
    python crop_yield_pipeline.py --data crop_yield_data.csv

    Optional:  --outdir images  --results results.json  --trees 60  --grid 40
    Quick smoke test:  python crop_yield_pipeline.py --trees 5 --grid 8

NOTE ON THE DATA
    The dataset is SYNTHETIC (generated by a program), see section 2. Treat every
    finding as a demonstration of METHOD, not as a statement about real farms.
"""

