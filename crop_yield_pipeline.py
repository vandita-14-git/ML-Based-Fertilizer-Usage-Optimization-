def what_if(forest, X_test, y_test, R, outdir):
    section("7. What-if test: extra tons from fertilizer, field by field")
    gain = forest.predict(X_test.assign(fertilized=1)) - forest.predict(X_test.assign(fertilized=0))
    crop_cols = [c for c in X_test.columns if c.startswith("crop_type_")]
    crop = X_test[crop_cols].idxmax(axis=1).str.replace("crop_type_", "")
    crop[X_test[crop_cols].sum(axis=1) == 0] = "corn"                 # corn = the dropped baseline
    model_by_crop = pd.Series(gain, index=X_test.index).groupby(crop).mean()
    raw = pd.DataFrame({"crop": crop, "fert": X_test["fertilized"], "y": y_test})
    raw_m = raw.groupby(["crop", "fert"])["y"].mean().unstack()
    raw_by_crop = raw_m[1] - raw_m[0]
    R["whatif"] = {"mean_gain": float(gain.mean()), "p5": float(np.percentile(gain, 5)),
                   "p95": float(np.percentile(gain, 95)), "min": float(gain.min()), "max": float(gain.max()),
                   "share_under_1": float((gain < 1.0).mean() * 100), "share_under_05": float((gain < 0.5).mean() * 100),
                   "by_crop_model": {k: float(v) for k, v in model_by_crop.items()},
                   "by_crop_raw": {k: float(v) for k, v in raw_by_crop.items()},
                   "max_model_vs_raw_difference": float((model_by_crop - raw_by_crop).abs().max())}
    print(f"Average gain {gain.mean():.2f} t | 5th-95th percentile {np.percentile(gain, 5):.2f} to {np.percentile(gain, 95):.2f}")

    fig, ax = plt.subplots(1, 2, figsize=(13, 4.8))
    ax[0].hist(gain, bins=50, color=C["blue"], edgecolor="white")
    ax[0].axvline(gain.mean(), color=C["red"], ls="--", label=f"average = {gain.mean():.2f} tons")
    ax[0].set_xlabel("Extra tons from fertilizer (model estimate)"); ax[0].set_ylabel("Number of fields")
    ax[0].set_title("What-if: benefit per field (spread is probably model noise)"); ax[0].legend()
    order = list(model_by_crop.index)
    x = np.arange(len(order)); w = 0.38
    ax[1].bar(x - w / 2, model_by_crop[order], w, color=C["green"], label="What-if (model)")
    ax[1].bar(x + w / 2, raw_by_crop[order], w, color=C["gray"], label="Raw gap (data)")
    ax[1].set_xticks(x); ax[1].set_xticklabels(order)
    ax[1].set_ylim(0, 3); ax[1].set_ylabel("Extra yield (tons)")
    ax[1].set_title("Model agrees with the raw data in every crop"); ax[1].legend(loc="lower right")
    save(fig, outdir, "13_fertilizer_whatif.png")


