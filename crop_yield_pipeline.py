def load_and_profile(path, R, outdir):
    section("1. Load and profile the raw data")
    df = pd.read_csv(path)
    missing = df.isnull().sum()
    R["raw"] = {"rows": int(len(df)), "columns": int(df.shape[1]),
                "missing_cells": {c: int(v) for c, v in missing.items() if v > 0}}
    R["categories"] = {c: {str(k): int(v) for k, v in df[c].value_counts().items()} for c in CAT_COLS}
    print(f"Rows: {len(df):,} | Columns: {df.shape[1]}")
    print("Missing cells:", R["raw"]["missing_cells"])

    # Chart: where are the gaps?
    miss = (missing[missing > 0] / len(df) * 100).sort_values()
    fig, ax = plt.subplots(figsize=(8, 4.6))
    ax.barh(miss.index, miss.values, color=[C["red"] if v > 5 else C["light"] for v in miss.values])
    for i, v in enumerate(miss.values):
        ax.text(v + 0.2, i, f"{v:.2f}%", va="center", fontsize=9)
    ax.set_xlabel("Share of rows with an empty cell (%)")
    ax.set_title("Three columns are missing 8-12% of values; the rest almost nothing")
    ax.set_xlim(0, miss.max() * 1.18)
    save(fig, outdir, "01_missing_values.png")
    return df


