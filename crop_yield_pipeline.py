# ============================================================================
def gain_by_group(df):
    """Fertilized-minus-unfertilized average yield inside each crop, soil, rainfall and temperature group."""
    rows = []
    for prefix, col, bands in [("crop", "crop_type", None), ("soil", "soil_type", None),
                               ("rain band", "rainfall_mm", 5), ("temp band", "avg_temp_c", 5)]:
        d = df.copy()
        if bands:
            d[col] = pd.qcut(d[col], bands, labels=False, duplicates="drop") + 1
        t = d.groupby([col, "fertilized"], observed=True)[TARGET].mean().unstack()
        for k, row in t.iterrows():
            label = f"{prefix}: {k}" if not bands else f"{prefix} {k} of {bands}"
            rows.append((prefix, label, float(row["yes"] - row["no"])))
    return rows


def explore(clean, R, outdir):
    section("4. Explore")
    y = clean[TARGET]
    R["target"] = {"mean": float(y.mean()), "median": float(y.median()), "std": float(y.std()),
                   "skew": float(y.skew()), "min": float(y.min()), "max": float(y.max()),
                   "negative": int((y < 0).sum()), "zero": int((y == 0).sum())}

    # 4a. target distribution
    fig, ax = plt.subplots(1, 2, figsize=(12, 4.4))
    ax[0].hist(y, bins=50, color=C["blue"], edgecolor="white")
    ax[0].axvline(y.mean(), color=C["red"], ls="--", label=f"mean = {y.mean():.1f}")
    ax[0].set_xlabel("Crop yield (tons)"); ax[0].set_ylabel("Number of fields")
    ax[0].set_title(f"Yield is a clean bell curve (skew {y.skew():.2f})"); ax[0].legend()
    ax[1].boxplot(y, vert=True)
    ax[1].set_ylabel("Crop yield (tons)"); ax[1].set_title("Boxplot: tails are natural, not errors")
    ax[1].set_xticks([])
    save(fig, outdir, "03_target_distribution.png")

    # 4b. fertilizer effect on raw averages
    means = clean.groupby("fertilized")[TARGET].mean()
    gap = float(means["yes"] - means["no"])
    R["fertilizer_raw"] = {"mean_no": float(means["no"]), "mean_yes": float(means["yes"]), "gap": gap,
                           "share_fertilized": float((clean["fertilized"] == "yes").mean())}
    fig, ax = plt.subplots(1, 2, figsize=(11, 4.4))
    clean.boxplot(column=TARGET, by="fertilized", ax=ax[0], grid=False)
    ax[0].set_title("Yield by fertilized"); ax[0].set_xlabel("fertilized"); ax[0].set_ylabel("Yield (tons)")
    fig.suptitle("")
    bars = ax[1].bar(["Not fertilized", "Fertilized"], [means["no"], means["yes"]], color=[C["gray"], C["green"]])
    for b in bars:
        ax[1].text(b.get_x() + b.get_width() / 2, b.get_height() + 0.2, f"{b.get_height():.2f}", ha="center")
    ax[1].set_ylabel("Average yield (tons)"); ax[1].set_ylim(0, means.max() * 1.15)
    ax[1].set_title(f"Fertilized fields yield {gap:.2f} tons more")
    save(fig, outdir, "04_fertilizer_effect.png")

    # 4c. correlations with yield
    corr = clean[INPUTS + [TARGET]].corr()[TARGET].drop(TARGET).sort_values()
    R["correlation_with_yield"] = {k: float(v) for k, v in corr.items()}
    fig, ax = plt.subplots(figsize=(7.5, 4.6))
    ax.barh(corr.index, corr.values, color=[C["red"] if v < 0 else C["blue"] for v in corr.values])
    ax.axvline(0, color="black", lw=0.8)
    ax.set_xlabel("Correlation with yield (-1 to +1)")
    ax.set_title("No single fact is strongly correlated with yield")
    save(fig, outdir, "05_correlations.png")

    # 4d. hills: real averages vs a straight-line fit
    fig, ax = plt.subplots(1, 2, figsize=(13, 4.6))
    R["hills"] = {}
    for a, col, label in [(ax[0], "rainfall_mm", "Rainfall (mm)"), (ax[1], "avg_temp_c", "Average temperature (C)")]:
        bins = pd.qcut(clean[col], 15, duplicates="drop")
        g = clean.groupby(bins, observed=True).agg(x=(col, "mean"), y=(TARGET, "mean"))
        slope, intercept = np.polyfit(clean[col], y, 1)
        r = float(clean[col].corr(y))
        a.plot(g["x"], g["y"], "o-", color=C["green"], lw=2.5, label="real average yield (a hill)")
        xs = np.linspace(g["x"].min(), g["x"].max(), 50)
        a.plot(xs, slope * xs + intercept, "--", color=C["red"], lw=2.5, label=f"straight-line fit (correlation {r:.2f})")
        a.set_xlabel(label); a.set_ylabel("Average yield (tons)"); a.legend(loc="lower center")
        a.set_title(f"Yield vs {col.split('_')[0]}: best in the middle")
        R["hills"][col] = {"correlation": r, "peak_at": float(g["x"].iloc[int(g["y"].values.argmax())]),
                           "peak_yield": float(g["y"].max()), "lowest_yield": float(g["y"].min())}
    save(fig, outdir, "06_hill_shapes.png")

    # 4e. does the fertilizer gain depend on conditions?
    groups = gain_by_group(clean)
    gains = [g[2] for g in groups]
    R["gain_by_group"] = {"min": float(min(gains)), "max": float(max(gains)), "overall": gap,
                          "groups": {g[1]: g[2] for g in groups}}
    palette = {"crop": C["blue"], "soil": C["orange"], "rain band": C["green"], "temp band": C["purple"]}
    fig, ax = plt.subplots(figsize=(8, 8))
    ax.barh([g[1] for g in groups][::-1], gains[::-1], color=[palette[g[0]] for g in groups][::-1])
    ax.axvline(gap, color="black", ls="--", label=f"overall gap = {gap:.2f}")
    ax.set_xlim(0, 3); ax.set_xlabel("Extra yield with fertilizer (tons)")
    ax.set_title("Fertilizer gain is about the same in every group")
    ax.legend(loc="lower right")
    save(fig, outdir, "07_fertilizer_gain_by_condition.png")
    print(f"Fertilizer gain across all groups: {min(gains):.2f} to {max(gains):.2f} tons (overall {gap:.2f})")
    return gap


