BOX = {"blue": ("#DCE7F5", "#4C72B0"), "green": ("#D8EFE3", "#2E8B57"), "orange": ("#FBE6D4", "#DD8452"),
       "red": ("#F6DADA", "#C44E52"), "gray": ("#ECEFF2", "#8C96A0"), "purple": ("#E6E1F3", "#7B6BB5")}


def draw_flow(outdir, name, W, H, boxes, arrows, figw=12.5):
    """boxes: {key: (cx, cy, w, h, title, subtitle, colour)}; arrows: list of point lists (last point gets the arrowhead)."""
    fig, ax = plt.subplots(figsize=(figw, figw * H / W))
    ax.set_xlim(0, W); ax.set_ylim(0, H); ax.axis("off")
    for cx, cy, w, h, title, sub, col in boxes.values():
        fc, ec = BOX[col]
        ax.add_patch(FancyBboxPatch((cx - w / 2, cy - h / 2), w, h, boxstyle="round,pad=0.3,rounding_size=1.6",
                                    fc=fc, ec=ec, lw=1.8))
        ax.text(cx, cy + (h * 0.22 if sub else 0), title, ha="center", va="center", fontsize=10.5, fontweight="bold")
        if sub:
            ax.text(cx, cy - h * 0.18, sub, ha="center", va="center", fontsize=8.6, color="#333", linespacing=1.3)
    for pts in arrows:
        for a, b in zip(pts[:-2], pts[1:-1]):
            ax.plot([a[0], b[0]], [a[1], b[1]], color="#444", lw=1.8, solid_capstyle="round")
        ax.annotate("", xy=pts[-1], xytext=pts[-2], arrowprops=dict(arrowstyle="-|>", color="#444", lw=1.8, shrinkA=0, shrinkB=0))
    fig.savefig(os.path.join(outdir, name), dpi=130, bbox_inches="tight", facecolor="white")
    plt.close(fig)
    print("   saved", name, flush=True)


