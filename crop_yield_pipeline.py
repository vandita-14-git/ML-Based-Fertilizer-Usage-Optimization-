def reality_check(df, R, outdir):
    section("2. Reality check: does the data behave like real farms?")
    temp = df.groupby("season")["avg_temp_c"].mean()
    rain = df.groupby("weather_zone")["rainfall_mm"].mean()
    hum = df.groupby("weather_zone")["humidity_pct"].mean()
    nutr = df.groupby("soil_type")[NUTRIENTS].mean()
    corr = df[INPUTS].corr()
    largest = float(np.triu(corr.abs().values, 1).max())     # strongest link between two DIFFERENT inputs
    R["reality"] = {"temp_by_season": temp.round(2).to_dict(), "rain_by_zone": rain.round(1).to_dict(),
                    "humidity_by_zone": hum.round(2).to_dict(),
                    "nutrients_by_soil": nutr.round(1).to_dict(), "largest_input_correlation": largest}
    print("Temperature by season:", temp.round(1).to_dict())
    print("Rainfall by zone     :", rain.round(0).to_dict())
    print(f"Largest correlation between any two inputs: {largest:.3f}")

    fig, ax = plt.subplots(1, 3, figsize=(16, 4.8))
    ax[0].bar(temp.index, temp.values, color=C["light"])
    for i, v in enumerate(temp.values):
        ax[0].text(i, v + 0.5, f"{v:.1f}", ha="center")
    ax[0].set_ylim(0, 32); ax[0].set_ylabel("Average temperature (C)")
    ax[0].set_title("Same temperature in every season")
    ax[1].bar(rain.index, rain.values, color=C["light"])
    for i, v in enumerate(rain.values):
        ax[1].text(i, v + 15, f"{v:.0f}", ha="center")
    ax[1].set_ylim(0, 1000); ax[1].set_ylabel("Average rainfall (mm)")
    ax[1].set_title('Same rainfall in every zone, even "dry"')
    im = ax[2].imshow(corr.values, cmap="RdBu_r", vmin=-1, vmax=1)
    labels = [SHORT[c] for c in INPUTS]
    ax[2].set_xticks(range(len(labels))); ax[2].set_xticklabels(labels, rotation=45, ha="right")
    ax[2].set_yticks(range(len(labels))); ax[2].set_yticklabels(labels)
    for i in range(len(labels)):
        for j in range(len(labels)):
            ax[2].text(j, i, f"{nz(corr.values[i, j]):.2f}", ha="center", va="center", fontsize=6.5)
    ax[2].set_title(f"Inputs are unrelated (largest link {largest:.3f})")
    fig.colorbar(im, ax=ax[2], fraction=0.046)
    ax[2].spines[:].set_visible(False)
    fig.suptitle("Reality check: this data does not behave like real farms, so it is synthetic",
                 fontsize=13, fontweight="bold", y=1.04)
    save(fig, outdir, "02_reality_check.png")


