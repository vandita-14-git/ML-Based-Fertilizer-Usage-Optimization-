def plateau_at(curves, col, pct=PCT_RULE):
    """First nutrient amount at which the curve has earned `pct` of its total gain (the 'phone battery' rule)."""
    grid, pred = curves[col]
    target = pred[0] + pct * (pred[-1] - pred[0])
    return float(grid[int(np.argmax(pred >= target))])


def plateau_analysis(forest, X_train, X_test, n_grid, R, outdir, fills):
    section("8. Nutrient curves and the 95% plateau rule")
    sample = X_test.sample(6000, random_state=SEED)
    curves = {}
    for col in NUTRIENTS:
        grid = np.linspace(X_train[col].quantile(0.02), X_train[col].quantile(0.98), n_grid)
        pred = np.array([forest.predict(sample.assign(**{col: v})).mean() for v in grid])
        curves[col] = (grid, pred)
        print(f"   curve for {col}: {pred[0]:.2f} -> {pred[-1]:.2f} tons")
    X_all = pd.concat([X_train, X_test], ignore_index=True)

    R["plateau"] = {}
    for col in NUTRIENTS:
        grid, pred = curves[col]
        p = plateau_at(curves, col)
        over = X_all[col] > p
        excess = X_all.loc[over, col] - p
        target = pred[0] + PCT_RULE * (pred[-1] - pred[0])
        R["plateau"][col] = {"start_amount": float(grid[0]), "end_amount": float(grid[-1]),
                             "start_yield": float(pred[0]), "end_yield": float(pred[-1]),
                             "total_gain": float(pred[-1] - pred[0]), "line_95": float(target), "plateau": p,
                             "kg_beyond_plateau": float(grid[-1] - p),
                             "tons_beyond_plateau": float(pred[-1] - pred[int(np.argmax(pred >= target))]),
                             "fields_above_pct": float(over.mean() * 100), "average_excess": float(excess.mean()),
                             "excess_share_pct": float(excess.sum() / X_all[col].sum() * 100)}
        print(f"   {col}: plateau {p:.0f} | fields above {over.mean() * 100:.1f}%")

    # 8a. the rule drawn on the real nitrogen curve
    col = "nitrogen_kg_ha"; grid, pred = curves[col]; P = R["plateau"][col]
    fig, ax = plt.subplots(figsize=(9.5, 5.8))
    ax.plot(grid, pred, color=C["green"], lw=3, label="Forest curve (average predicted yield)")
    ax.axhline(P["start_yield"], color="gray", ls=":", lw=1.5); ax.axhline(P["end_yield"], color="gray", ls=":", lw=1.5)
    ax.axhline(P["line_95"], color=C["orange"], ls="--", lw=2, label=f"95% line = {P['line_95']:.2f} tons")
    ax.axvline(P["plateau"], color=C["red"], lw=2.5, label=f"Plateau = {P['plateau']:.0f} kg/ha")
    ax.axvspan(P["plateau"], grid[-1], color=C["red"], alpha=0.10)
    ax.annotate(f"START: {P['start_yield']:.2f} t", (grid[0], pred[0]), xytext=(grid[0] + 8, pred[0] + 0.12), arrowprops=dict(arrowstyle="->"))
    ax.annotate(f"END: {P['end_yield']:.2f} t", (grid[-1], pred[-1]), xytext=(grid[-1] - 75, pred[-1] - 0.35), arrowprops=dict(arrowstyle="->"))
    ax.annotate("", xy=(grid[0] - 3, pred[-1]), xytext=(grid[0] - 3, pred[0]), arrowprops=dict(arrowstyle="<->"))
    ax.text(grid[0] + 2, (pred[0] + pred[-1]) / 2, f"total gain\n{P['total_gain']:.2f} t", va="center")
    ax.text(P["plateau"] + 5, pred[0] + 0.55, "beyond the plateau:\nvery little gain", color=C["red"])
    ax.set_xlabel("Nitrogen (kg/ha)"); ax.set_ylabel("Average predicted yield (tons)")
    ax.set_title("How the plateau is found (nitrogen)"); ax.legend(loc="lower right"); ax.grid(alpha=0.3)
    save(fig, outdir, "14_plateau_rule_nitrogen.png")

    # 8b. all three nutrient curves
    fig, axes = plt.subplots(1, 3, figsize=(16, 4.6))
    for ax, col in zip(axes, NUTRIENTS):
        grid, pred = curves[col]; p = R["plateau"][col]["plateau"]
        ax.plot(grid, pred, color=C["green"], lw=2.5)
        ax.axvline(p, color=C["red"], lw=2, label=f"plateau = {p:.0f} kg/ha")
        ax.axvspan(p, grid[-1], color=C["red"], alpha=0.10)
        ax.set_title(col.replace("_kg_ha", "").capitalize())
        ax.set_xlabel("Amount (kg/ha)"); ax.set_ylabel("Average predicted yield (tons)"); ax.legend(loc="lower right")
    fig.suptitle("Yield stops responding once each nutrient passes its plateau (note: different y-scales)",
                 fontsize=12, fontweight="bold", y=1.03)
    save(fig, outdir, "15_nutrient_plateaus.png")

    # 8c. how many fields lie beyond the plateau
    fig, axes = plt.subplots(1, 3, figsize=(16, 4.6))
    for ax, col in zip(axes, NUTRIENTS):
        p = R["plateau"][col]["plateau"]
        ax.hist(X_all[col], bins=60, color=C["light"], edgecolor="white")
        ax.axvline(p, color=C["red"], lw=2.5, label=f"plateau = {p:.0f}")
        ax.axvspan(p, X_all[col].max(), color=C["red"], alpha=0.12)
        ax.set_title(f"{col.replace('_kg_ha', '').capitalize()}: {R['plateau'][col]['fields_above_pct']:.1f}% of fields above")
        ax.set_xlabel("Amount (kg/ha)"); ax.set_ylabel("Number of fields"); ax.legend()
        if col in fills:
            m = fills[col]["median_used"]
            ax.annotate("spike = cells filled\nwith the median", (m, ax.get_ylim()[1] * 0.92),
                        xytext=(m + (X_all[col].max() - X_all[col].min()) * 0.18, ax.get_ylim()[1] * 0.78),
                        arrowprops=dict(arrowstyle="->"), fontsize=9)
    save(fig, outdir, "16_fields_beyond_plateau.png")

    # 9a. sensitivity to the rule
    section("9. Sensitivity to the rule, and the trim test")
    sens = []
    for col in NUTRIENTS:
        for pct in (0.90, 0.95, 0.99):
            p = plateau_at(curves, col, pct)
            sens.append({"nutrient": col.replace("_kg_ha", ""), "rule": f"{int(pct * 100)}%", "plateau": p,
                         "fields_above_pct": float((X_all[col] > p).mean() * 100)})
    R["sensitivity"] = sens
    fig, ax = plt.subplots(figsize=(8.5, 4.8))
    x = np.arange(3); w = 0.26
    for i, (rule, color) in enumerate([("90%", C["orange"]), ("95%", C["green"]), ("99%", C["blue"])]):
        vals = [next(s["fields_above_pct"] for s in sens if s["nutrient"] == n.replace("_kg_ha", "") and s["rule"] == rule) for n in NUTRIENTS]
        bars = ax.bar(x + (i - 1) * w, vals, w, color=color, label=f"{rule} rule")
        for b, v in zip(bars, vals):
            ax.text(b.get_x() + b.get_width() / 2, v + 0.3, f"{v:.1f}", ha="center", fontsize=9)
    ax.set_xticks(x); ax.set_xticklabels([n.replace("_kg_ha", "") for n in NUTRIENTS])
    ax.set_ylabel("Fields above the plateau (%)"); ax.legend()
    ax.set_title("The headline number depends on the rule, so report a range")
    save(fig, outdir, "17_sensitivity.png")

    # 9b. trim every field down to its plateau and ask the forest what happens to yield
    capped = X_test.copy()
    for col in NUTRIENTS:
        capped[col] = np.minimum(capped[col], R["plateau"][col]["plateau"])
    before, after = forest.predict(X_test), forest.predict(capped)
    change = after - before
    saved = {c: float((X_test[c] - capped[c]).mean() / X_test[c].mean() * 100) for c in NUTRIENTS}
    saved_kg = {c: float((X_test[c] - capped[c]).mean()) for c in NUTRIENTS}
    R["cap"] = {"mean_before": float(before.mean()), "mean_after": float(after.mean()),
                "mean_change": float(change.mean()), "mean_change_pct": float(change.mean() / before.mean() * 100),
                "share_losing_over_half_ton": float((change < -0.5).mean() * 100),
                "share_unchanged": float((capped[NUTRIENTS].values == X_test[NUTRIENTS].values).all(axis=1).mean() * 100),
                "saved_pct": saved, "saved_kg_per_field": saved_kg}
    print(f"   trim test: yield change {change.mean():+.3f} t ({change.mean() / before.mean() * 100:+.2f}%) | saved % {saved}")


