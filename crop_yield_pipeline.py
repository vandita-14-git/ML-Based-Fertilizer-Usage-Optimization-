def nz(v, tol=0.005):
    """Show tiny values (including -0.000) as 0 so labels never read "-0.00"."""
    return 0.0 if abs(v) < tol else v


def rmse(actual, predicted):
    """Typical size of a mistake, in the same unit as the target (tons)."""
    return float(np.sqrt(mean_squared_error(actual, predicted)))


def section(title):
    print(f"\n{'=' * 78}\n{title}\n{'=' * 78}", flush=True)


